import hashlib

def stat(tag, p):
    b = open(p, 'rb').read()
    ls = b.split(b'\n')
    cr = sum(1 for l in ls if l.endswith(b'\r'))
    print('  %-10s %8d B  md5 %s  CRLF %d  BARE_LF %d'
          % (tag, len(b), hashlib.md5(b).hexdigest(), cr, len(ls) - 1 - cr))
    return b

def patch(p, old, new, label, append_at_end=None):
    print('\n【%s】%s' % (label, p.split('/')[-1]))
    b = stat('改前', p)
    assert b'\r' not in b, '非纯 LF，中止：' + p
    s = b.decode('utf-8')
    if old is not None:
        n = s.count(old)
        print('  old 命中 %d 次 → %s' % (n, old[:60].replace('\n', '\\n')))
        assert n == 1, 'old 命中数不为 1，中止（未写盘）'
        s = s.replace(old, new)
    if append_at_end:
        if not s.endswith('\n'):
            s += '\n'
        s += append_at_end
    open(p, 'wb').write(s.encode('utf-8'))
    stat('改后', p)


"""C51 §五 1-3 项更正：byte 级、只增不删、保持纯 LF、改后回验。"""
import hashlib, os, re

def stat(tag, p):
    b = open(p, 'rb').read()
    ls = b.split(b'\n')
    cr = sum(1 for l in ls if l.endswith(b'\r'))
    print('%-46s %7d B  md5 %s  CRLF %d  BARE_LF %d'
          % (tag, len(b), hashlib.md5(b).hexdigest(), cr, len(ls) - 1 - cr))
    return b

def apply(p, pairs, tail_anchor, tail_add, tag):
    print('\n' + '=' * 92)
    print('【%s】%s' % (tag, os.path.basename(p)))
    b0 = stat('改前', p)
    s = b0.decode('utf-8')
    for old, new in pairs:
        n = s.count(old)
        print('  替换命中 %d 次 ← %s' % (n, old[:56].replace('\n', '\\n')))
        assert n == 1, '命中数不为 1，中止（未写盘）'
        s = s.replace(old, new)
    n = s.count(tail_anchor)
    print('  锚点命中 %d 次 ← %s' % (n, tail_anchor[:56].replace('\n', '\\n')))
    assert n == 1, '锚点命中数不为 1，中止（未写盘）'
    s = s.replace(tail_anchor, tail_anchor + tail_add)
    data = s.encode('utf-8')
    # 纯 LF 保持：把任何裸 CR 归一（本批 .md 定版 LF）
    assert b'\r' not in data, '出现 CR，中止（未写盘）'
    open(p, 'wb').write(data)
    stat('改后', p)



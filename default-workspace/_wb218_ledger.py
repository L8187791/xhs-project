ptr = ("> 🟢 **已结案（L 2026-10-17 20:0x 裁定）**：两套数不是数据错误，是**滚动 7 天窗口位移** → 详见下方 §七·补三。"
       "本节表格与下方「-31%／-28%／+6%／+43%／-10%」**跨窗口环比已作废、禁再引用**；表格本身保留为历史留痕。\n")
